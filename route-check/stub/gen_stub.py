"""Generate a fake Linux libcuda.so.1 for the zluda32 route check.

  gen_stub.py SVESOP_NVCUDA_C OUT_C

SveSop's nvcuda refuses to load unless every LOAD_FUNCPTR symbol resolves, so
every name it loads gets a stub returning CUDA_ERROR_NOT_SUPPORTED. The calls
the route needs are implemented in stub_impl.c. Its ZLUDA32_INTERNAL table
uses the SysV ABI, like ZLUDA's Linux libcuda.
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1]).read_text()
names = sorted(set(re.findall(r'\b(?:TRY_)?LOAD_FUNCPTR\((\w+)\)', src)))
impl = set(re.findall(r'^CUresult (\w+)\(', (Path(__file__).parent / 'stub_impl.c').read_text(), re.M))
out = ['/* generated by gen_stub.py */', '#include "stub_impl.c"']
out += [f'int {n}(void) {{ stub_unimplemented("{n}"); return 801; }}' for n in names if n not in impl]
Path(sys.argv[2]).write_text('\n'.join(out) + '\n')
print(f'{len(names)} symbols loaded by nvcuda, {len(impl)} implemented', file=sys.stderr)
missing = sorted(impl - set(names) - {'cuGetExportTable'})
if missing:
    print('implemented but not loaded by nvcuda: ' + ' '.join(missing), file=sys.stderr)
